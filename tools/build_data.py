def encode(grid):
    out = []
    for r in ROWS:
        for c in COLS:
            hexv = grid.get(f"{c}{r}", "#ffffff")
            try:
                out.append(CHARS[PALETTE.index(hexv)])
            except ValueError:
                out.append("0")
    return "".join(out)


def clean(text):
    return (text.replace('"', "").replace("  ", " ").strip() if text else "")


def main():
    src = Path(sys.argv[1])
    out_path = Path(sys.argv[2])
    raw = json.loads(src.read_text(encoding="utf-8"))

    songs_out = []
    for cfg, song in zip(SONGS, raw[:10]):
        # True run order (confirmed against the source sheets): read each
        # block-column top -> bottom, then jump back to the top of the next
        # block-column and continue down.  Block columns repeat every 16 tds
        # (15 seat columns + 1 separator), bands are the rows of blocks.
        old_order = cfg["order"]
        run = sorted(
            old_order,
            key=lambda bi: (
                (song["steps"][bi].get("c0", 1) - 1) // 16,
                song["steps"][bi].get("band", 0),
            ),
        )
        # names / cues / insights are authored against the curated old order
        old_pos_of = {bi: pos for pos, bi in enumerate(old_order)}
        steps = []
        for pos, bi in enumerate(run):
            s = song["steps"][bi]
            old_pos = old_pos_of[bi]
            steps.append({
                "code": f'{cfg["id"]}.{pos + 1}',
                "name": cfg["names"][old_pos],
                "cue": CUES[cfg["id"]][old_pos],
                "insight": cfg["insights"].get(old_pos, ""),
                "g": encode(s["grid"]),
            })
        songs_out.append({
            "id": cfg["id"], "code": cfg["code"], "file": cfg["file"],
            "title": cfg["title"], "subtitle": cfg["subtitle"],
            "theme": cfg["theme"], "desc": cfg["desc"],
            "showCode": {1: "2", 2: "3", 3: "4", 4: "6", 5: "7",
                         6: "8", 7: "9", 8: "10", 9: "14–15", 10: "17"}[cfg["id"]],
            "lyrics": LYRICS[cfg["id"]],
            "notation": NOTATION[cfg["id"]],
            "rawBlocks": len(song["steps"]),
            "steps": steps,
        })

    colors_out = {}
    for hexv, (short, name, desc, text) in COLOR_META.items():
        colors_out[hexv] = {"short": short, "name": name, "desc": desc, "text": text}

    bundle = {
        "meta": {
            "school": "โรงเรียนพิริยาลัยจังหวัดแพร่",
            "team": "ลูกผึ้ง ขาว–แดง",
            "cols": COLS,
            "rows": ROWS,
            "palette": PALETTE,
            "chars": CHARS,
            "totalSeats": 150,
        },
        "colors": colors_out,
        "songs": songs_out,
        "show": SHOW,
        "songbook": SONGBOOK,
        "program": PROGRAM,
        "equipment": EQUIPMENT,
        "typos": TYPOS,
    }
    out_path.write_text(
        "const APP_DATA = " + json.dumps(bundle, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    total = sum(len(s["steps"]) for s in songs_out)
    print("songs:", len(songs_out), "steps:", total, "bytes:", out_path.stat().st_size)


if __name__ == "__main__":
    main()
